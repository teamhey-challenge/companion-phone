android {
    namespace = "ai.hey.phone"
    compileSdk = 36
    defaultConfig {
        applicationId = "ai.hey.phone"
        minSdk = 28
        targetSdk = 35
        // Monotonic and identical for CI and local builds of the same commit: the commit count (CI checks out with fetch-depth 0).
        // -Phey.versionCode=N overrides; without git history it falls back to 1.
        versionCode = providers.gradleProperty("hey.versionCode").map { it.toInt() }.orElse(
            providers.exec { commandLine("git", "rev-list", "--count", "HEAD"); isIgnoreExitValue = true }
                .standardOutput.asText.map { it.trim().toIntOrNull() ?: 1 }
        ).get()
        versionName = providers.gradleProperty("hey.versionName").get()
    }
    // Release signing: HEYPARRI_STORE_FILE / HEYPARRI_STORE_PASSWORD / HEYPARRI_KEY_ALIAS (CI release-apk job, key password =
    // store password), else the 600 properties file outside the repo. Neither present: release falls back to the debug key
    // (the debug CI path has no key material and keeps building).
    val signingFile = File(System.getProperty("user.home"), ".config/hey/signing.properties")
    val envStore = System.getenv("HEYPARRI_STORE_FILE")
    val releaseSigning = if (envStore != null) {
        signingConfigs.create("release") {
            storeFile = file(envStore)
            storePassword = System.getenv("HEYPARRI_STORE_PASSWORD")
            keyAlias = System.getenv("HEYPARRI_KEY_ALIAS")
            keyPassword = System.getenv("HEYPARRI_STORE_PASSWORD")
            enableV2Signing = true
            enableV3Signing = true // key rotation / lineage (Pleos: API 28+)
        }
    } else if (signingFile.isFile) {
        val p = Properties().apply { signingFile.inputStream().use { load(it) } }
        signingConfigs.create("release") {
            storeFile = file(p.getProperty("storeFile"))
            storePassword = p.getProperty("storePassword")
            keyAlias = p.getProperty("keyAlias")
            keyPassword = p.getProperty("keyPassword")
            enableV2Signing = true
            enableV3Signing = true
        }
    } else signingConfigs.getByName("debug")
    // Google sign-in: the *web* OAuth client id the server checks as `aud` (public, not a secret; the same value as the server's
    // GOOGLE_WEB_CLIENT_ID). Override with -PgoogleServerClientId=...; an explicit empty value turns the Google button off
    // ("지금은 구글 로그인을 쓸 수 없어요") while the QR path keeps working.
    val googleServerClientId = providers.gradleProperty("googleServerClientId")
        .getOrElse("1078450288189-iiq707dvvm68jstcbrmfck8pahon9a8p.apps.googleusercontent.com")
    require(Regex("[A-Za-z0-9._-]*").matches(googleServerClientId)) { "googleServerClientId has unexpected characters" }
    defaultConfig { buildConfigField("String", "GOOGLE_SERVER_CLIENT_ID", "\"$googleServerClientId\"") }
    // Companion server (same API as the phone web). https only. Override with -PserverUrl=https://...
    val serverUrl = providers.gradleProperty("serverUrl").getOrElse("https://hey.lastmile.ltd/api")
    require(serverUrl.startsWith("https://")) { "serverUrl must be https" }
    // e2e only (debug and releaseE2e, never release): plain-http test server. -Pe2eServerUrl=http://<host>:<port>
    // The host is written into a generated cleartext allow-list (build/generated/e2e-res); no host is baked into the repo.
    val e2eServerUrl = providers.gradleProperty("e2eServerUrl").orNull
    val e2eMatch = e2eServerUrl?.let { Regex("http://([A-Za-z0-9.-]+):\\d+").matchEntire(it) }
    require(e2eServerUrl == null || e2eMatch != null) { "e2eServerUrl must be http://<host>:<port>" }
    val debugServerUrl = e2eServerUrl ?: serverUrl
    val e2eResDir = layout.buildDirectory.dir("generated/e2e-res").get().asFile
    File(e2eResDir, "xml").apply { mkdirs() }.resolve("network_security.xml").writeText(
        """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/build.gradle.kts. debug and releaseE2e only: plain http to the e2e test server. Release keeps the main config. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">${e2eMatch?.groupValues?.get(1) ?: "10.0.2.2"}</domain>
    </domain-config>
</network-security-config>
""",
    )
    buildTypes {
        debug { buildConfigField("String", "SERVER_URL", "\"$debugServerUrl\"") }
        release {
            buildConfigField("String", "SERVER_URL", "\"$serverUrl\"")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = releaseSigning
        }
        // R8 proof: minified and shrunk exactly like release but debug-signed. Never shipped. Build: ./gradlew :app:assembleReleaseE2e
        create("releaseE2e") {
            initWith(getByName("release"))
            matchingFallbacks += "release"
            buildConfigField("String", "SERVER_URL", "\"$debugServerUrl\"")
            signingConfig = signingConfigs.getByName("debug")
        }
    }
    // Cleartext to the e2e host (generated above) is compiled into debug and releaseE2e only; release keeps the https-only main config.
    sourceSets {
        getByName("debug") { res.srcDir(e2eResDir) }
        getByName("releaseE2e") { res.srcDir(e2eResDir) }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    testOptions { unitTests { isReturnDefaultValues = true; isIncludeAndroidResources = true } }
}

